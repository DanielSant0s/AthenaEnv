#!/usr/bin/env python3
"""Embed Lua sources as C string constants for the AthenaEnv Lua runtime.

usage: lua2c.py out.c file1.lua [file2.lua ...]

Each file becomes `const char athena_lua_src_<name>[]` plus a size, where
<name> is the file name without extension.
"""
import os
import sys


def c_string(data):
    out = []
    for line in data.splitlines(keepends=True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "")
        esc = esc.replace("\n", "\\n")
        out.append('"' + esc + '"')
    return "\n".join(out) if out else '""'


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out_path, sources = sys.argv[1], sys.argv[2:]
    parts = ["/* Generated by scripts/lua2c.py -- do not edit. */", "#include <stddef.h>", ""]
    for src in sources:
        name = os.path.splitext(os.path.basename(src))[0]
        with open(src, encoding="utf-8") as f:
            data = f.read()
        parts.append("const char athena_lua_src_%s[] =\n%s;" % (name, c_string(data)))
        parts.append("const size_t athena_lua_src_%s_size = sizeof(athena_lua_src_%s) - 1;" % (name, name))
        parts.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
