#!/usr/bin/env python3
"""
Build-time LZ4 High-Compression (HC) asset & IRX embedder for AthenaEnv.

Produces a C file with:
  unsigned char <sym>[] __attribute__((aligned(16))) = { ... };
  unsigned int size_<sym> = ...;

Container format (when LZ4-compressed):
  Bytes 0..3:  Magic "ALZ4" (0x345A4C41 little-endian)
  Bytes 4..7:  Uncompressed size (uint32_t little-endian)
  Bytes 8..11: Compressed payload size (uint32_t little-endian)
  Bytes 12..N: Standard LZ4 block stream (compatible with athena_lz4_decompress)

If the input is tiny or incompressible, emits the raw bytes unchanged.
"""

import struct
import sys

LZ4_MINMATCH = 4
LZ4_LASTLITERALS = 5
LZ4_MFLIMIT = 12
LZ4_MAX_DISTANCE = 65535
ALZ4_MAGIC = b"ALZ4"


def lz4_compress_hc(data: bytes) -> bytes:
    """Optimal-parsing / deep-chain LZ4 block compressor compatible with standard LZ4 block decoder."""
    n = len(data)
    if n < 32:
        return b""

    out = bytearray()
    anchor = 0
    ip = 0
    limit = n - LZ4_MFLIMIT
    matchlimit = n - LZ4_LASTLITERALS

    # Hash chains: head[h] -> latest pos, prev[pos & 0xFFFF] -> previous pos with same 4-byte prefix
    from collections import defaultdict
    chains = defaultdict(list)

    def find_best_match(pos: int):
        if pos + 4 > limit:
            return 0, 0
        key = data[pos:pos + 4]
        bucket = chains.get(key)
        if not bucket:
            return 0, 0
        best_len = 0
        best_off = 0
        max_len = matchlimit - pos
        # Search recent occurrences from newest to oldest (up to 128 candidates)
        checked = 0
        for cand in reversed(bucket):
            off = pos - cand
            if off > LZ4_MAX_DISTANCE:
                break
            if off <= 0:
                continue
            # Quick check at best_len to skip shorter matches immediately
            if best_len >= 4 and data[cand + best_len] != data[pos + best_len]:
                checked += 1
                if checked >= 128:
                    break
                continue
            # Count match length
            ml = 4
            while ml < max_len and data[cand + ml] == data[pos + ml]:
                ml += 1
            if ml > best_len:
                best_len = ml
                best_off = off
                if ml == max_len:
                    break
            checked += 1
            if checked >= 128:
                break
        return best_len, best_off

    while ip < limit:
        ml, off = find_best_match(ip)
        chains[data[ip:ip + 4]].append(ip)

        if ml < LZ4_MINMATCH:
            ip += 1
            continue

        # Lazy matching: check if ip + 1 has a strictly better match (at least +2 bytes longer)
        if ip + 1 < limit:
            ml2, off2 = find_best_match(ip + 1)
            if ml2 > ml + 1:
                ip += 1
                chains[data[ip:ip + 4]].append(ip)
                ml, off = ml2, off2

        # Emit sequence (anchor..ip literals, then match of length ml at offset off)
        lit_len = ip - anchor
        ml_code = ml - LZ4_MINMATCH

        token = ((15 if lit_len >= 15 else lit_len) << 4) | (15 if ml_code >= 15 else ml_code)
        out.append(token)

        if lit_len >= 15:
            rem = lit_len - 15
            while rem >= 255:
                out.append(255)
                rem -= 255
            out.append(rem)

        if lit_len > 0:
            out.extend(data[anchor:ip])

        # 16-bit little-endian offset
        out.append(off & 0xFF)
        out.append((off >> 8) & 0xFF)

        if ml_code >= 15:
            rem = ml_code - 15
            while rem >= 255:
                out.append(255)
                rem -= 255
            out.append(rem)

        # Advance through match and populate dictionary
        match_end = ip + ml
        step_limit = min(match_end, n - 4)
        p = ip + 1
        while p < step_limit:
            chains[data[p:p + 4]].append(p)
            p += 1

        ip = match_end
        anchor = ip

    # Emit last literals
    last_lit = n - anchor
    token = (15 if last_lit >= 15 else last_lit) << 4
    out.append(token)
    if last_lit >= 15:
        rem = last_lit - 15
        while rem >= 255:
            out.append(255)
            rem -= 255
        out.append(rem)
    if last_lit > 0:
        out.extend(data[anchor:n])

    return bytes(out)


def emit_c_array(out_path: str, sym_name: str, payload: bytes):
    lines = [
        "/* Auto-generated by scripts/bin2c_lz4.py */",
        f"unsigned char {sym_name}[] __attribute__((aligned(16))) = {{",
    ]
    row = []
    for i, b in enumerate(payload):
        row.append(f"0x{b:02x}")
        if len(row) == 16 or i == len(payload) - 1:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    lines.append("};")
    lines.append(f"unsigned int size_{sym_name} = {len(payload)};")
    lines.append("")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <input_file> <output_c_file> <symbol_name>", file=sys.stderr)
        sys.exit(1)

    in_path, out_path, sym_name = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(in_path, "rb") as f:
        raw = f.read()

    comp = lz4_compress_hc(raw)
    if comp and (len(comp) + 12 + 64 < len(raw)):
        header = struct.pack("<4sII", ALZ4_MAGIC, len(raw), len(comp))
        payload = header + comp
    else:
        payload = raw

    emit_c_array(out_path, sym_name, payload)


if __name__ == "__main__":
    main()
